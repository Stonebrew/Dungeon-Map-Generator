function getConnectionLayoutMetadata(style: MapStyle, connection: MapConnection): Pick<MapConnection, 'routeStyle' | 'routeDifficulty'> {
  if (connection.type === 'secret') {
    return { routeStyle: 'crawl', routeDifficulty: 'hidden' };
  }

  if (style === 'forestRuin') {
    return { routeStyle: 'trail', routeDifficulty: 'clear' };
  }

  if (style === 'cavern') {
    return { routeStyle: 'tunnel', routeDifficulty: connection.from === 5 || connection.to === 5 ? 'narrow' : 'clear' };
  }

  if (style === 'sewer') {
    return { routeStyle: connection.from === 5 || connection.to === 5 ? 'channel' : 'servicePath', routeDifficulty: 'narrow' };
  }

  if (style === 'volcanicForge') {
    const isBridge = (connection.from === 3 && connection.to === 4) || (connection.from === 4 && connection.to === 7);
    return { routeStyle: isBridge ? 'grate' : 'ledge', routeDifficulty: isBridge ? 'hazardous' : 'clear' };
  }

  if (style === 'shrine') {
    return { routeStyle: connection.from === 1 || connection.to === 1 ? 'causeway' : 'corridor', routeDifficulty: 'clear' };
  }

  if (style === 'crypt') {
    return { routeStyle: 'corridor', routeDifficulty: connection.from === 5 || connection.to === 5 ? 'narrow' : 'clear' };
  }

  if (style === 'laboratory') {
    return { routeStyle: 'servicePath', routeDifficulty: 'clear' };
  }

  if (style === 'frozenRuin') {
    const bridgePairs = new Set(['3-5', '5-8']);
    const key = [connection.from, connection.to].sort((a, b) => a - b).join('-');
    return { routeStyle: bridgePairs.has(key) ? 'bridge' : connection.from === 7 || connection.to === 7 ? 'tunnel' : 'trail', routeDifficulty: bridgePairs.has(key) ? 'hazardous' : 'clear' };
  }

  if (style === 'desertTemple') {
    const key = [connection.from, connection.to].sort((a, b) => a - b).join('-');
    if (key === '5-8') {
      return { routeStyle: 'stair', routeDifficulty: 'unstable' };
    }
    if (key === '1-7') {
      return { routeStyle: 'crawl', routeDifficulty: 'hidden' };
    }
    if (key === '2-5' || key === '5-6') {
      return { routeStyle: 'ledge', routeDifficulty: 'narrow' };
    }
    return { routeStyle: key === '1-2' || key === '2-3' ? 'trail' : 'causeway', routeDifficulty: 'clear' };
  }

  return { routeStyle: 'corridor', routeDifficulty: 'clear' };
}

function exitTypeForConnection(connection: MapConnection, roomNumber: number): RoomExit['type'] {
  if (connection.oneWay && connection.from === roomNumber) {
    return 'oneWay';
  }

  return connection.type;
}

function buildStructuredExits(dungeon: DraftDungeon, room: DraftRoom): RoomExit[] {
  const roomId = room.id ?? getRoomId(dungeon.id, room.number);

  return (dungeon.map.connections ?? [])
    .filter((connection) => connection.from === room.number || connection.to === room.number)
    .map((connection) => {
      const targetRoomNumber = connection.from === room.number ? connection.to : connection.from;
      const type = exitTypeForConnection(connection, room.number);

      return {
        id: `${roomId}-to-${getRoomId(dungeon.id, targetRoomNumber)}`,
        toRoomId: getRoomId(dungeon.id, targetRoomNumber),
        toRoomNumber: targetRoomNumber,
        type,
        label: connection.note ?? `${type === 'secret' ? 'Hidden route' : type === 'oneWay' ? 'One-way route' : 'Route'} to Room ${targetRoomNumber}`,
        description: room.exits,
        note: connection.note,
      };
    });
}

function finalizeDungeon(dungeon: DraftDungeon): Dungeon {
  return {
    ...dungeon,
    map: {
      ...dungeon.map,
      layout: dungeon.map.layout ?? mapLayoutGrammarByStyle[dungeon.map.style],
      connections: dungeon.map.connections?.map((connection) => ({
        ...getConnectionLayoutMetadata(dungeon.map.style, connection),
        ...connection,
      })),
    },
    rooms: dungeon.rooms.map((room) => ({
      ...roomLayoutMetadataByStyle[dungeon.map.style][room.number],
      ...room,
      id: room.id ?? getRoomId(dungeon.id, room.number),
      structuredExits: room.structuredExits ?? buildStructuredExits(dungeon, room),
    })),
  };
}

